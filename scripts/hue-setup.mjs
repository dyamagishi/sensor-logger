export function bridgeURL(input) {
  const url=new URL(input.includes('://')?input:`https://${input}`);
  if(url.protocol!=='https:'||url.username||url.password||url.pathname!=='/'||url.search||url.hash)throw Error('接続先はHTTPSのIPアドレスまたはホスト名で指定してください。');
  return url.origin;
}
const hostOf=url=>new URL(url).hostname.replace(/^\[|\]$/g,'');
const shellQuote=s=>`'${s.replace(/'/g,"'\\''")}'`;
const safeText=s=>String(s).replace(/[\x00-\x1f\x7f-\x9f]/g,'');
export async function certificateAt(url) {
  return new Promise((resolve,reject)=>{
    const socket=tls.connect({host:hostOf(url),port:Number(new URL(url).port)||443,servername:hostOf(url).includes(':')||/^\d+\.\d+\.\d+\.\d+$/.test(hostOf(url))?undefined:hostOf(url),rejectUnauthorized:false},()=>{
      const raw=socket.getPeerCertificate().raw;socket.end();
      if(!raw)reject(Error('証明書を取得できません。'));else resolve(new X509Certificate(raw));
    });
    socket.setTimeout(8000,()=>socket.destroy(Error('接続がタイムアウトしました。')));socket.once('error',reject);
  });
}
export function pinnedAgent(certificate) {
  const agent=new https.Agent({keepAlive:false});
  agent.createConnection=(options,callback)=>{
    let done=false;const finish=(error,socket)=>{if(!done){done=true;callback(error,socket);}};
    const socket=tls.connect({...options,rejectUnauthorized:false},()=>{
      const raw=socket.getPeerCertificate().raw;
      if(!raw||!raw.equals(certificate.raw)){const error=Error('Bridgeの証明書が変わりました。設定をやり直してください。');finish(error);socket.destroy();}
      else finish(null,socket);
    });
    socket.setTimeout(8000,()=>socket.destroy(Error('接続がタイムアウトしました。')));socket.once('error',error=>finish(error));
    // HTTP headers (including credentials) are sent only after pin verification.
  };
  return agent;
}
export async function bridgeRequest(url,path,certificate,{key,body}={}) {
  const agent=pinnedAgent(certificate);
  try{return await new Promise((resolve,reject)=>{
    const req=https.request(url+path,{agent,method:body?'POST':'GET',headers:{...(key?{'hue-application-key':key}:{}),...(body?{'Content-Type':'application/json'}:{})}},res=>{
      if(res.statusCode!==200){res.resume();reject(Error(`Hue HTTP ${res.statusCode}`));return;}
      let size=0;const chunks=[];res.on('data',chunk=>{size+=chunk.length;if(size>2_097_152){res.destroy(Error('応答が大きすぎます。'));return;}chunks.push(chunk);});
      res.once('error',reject);res.once('end',()=>{try{resolve(JSON.parse(Buffer.concat(chunks).toString('utf8')));}catch{reject(Error('Hueの応答を読めませんでした。'));}});
    });req.setTimeout(8000,()=>req.destroy(Error('接続がタイムアウトしました。')));req.once('error',reject);req.end(body?JSON.stringify(body):undefined);
  });}finally{agent.destroy();}
}
export async function writeConfiguration(output,{url,bridgeId,key,certificate,targetDir='/etc/home-sensors'}) {
  if(!/^[a-f0-9]{16}$/i.test(bridgeId)||!/^[a-z0-9_-]{1,128}$/i.test(key))throw Error('Bridgeの識別情報または認証情報が不正です。');
  if(!isAbsolute(targetDir)||/[\x00-\x1f]/.test(targetDir))throw Error('配置先は絶対パスで指定してください。');
  try{await stat(output);throw Error('出力先が既に存在します。別のディレクトリを指定してください。');}catch(e){if(e.code!=='ENOENT')throw e;}
  const parent=dirname(output);await mkdir(parent,{recursive:true,mode:0o700});
  const stage=await mkdtemp(join(parent,'.hue-setup-'));
  try{
    const config=`# Generated by hue-setup. Copy to ${join(targetDir,'hue.toml')}\nbridge_url = ${JSON.stringify(bridgeURL(url))}\nbridge_id = ${JSON.stringify(bridgeId.toLowerCase())}\ncertificate_file = ${JSON.stringify(join(targetDir,'hue-certificate.der'))}\nregistry_file = ${JSON.stringify(join(targetDir,'hue-devices.json'))}\n`;
    const env=`# Hue-only fragment. Source from /etc/home-sensors.env on OpenWrt.\nHUE_CONFIG_FILE=${shellQuote(join(targetDir,'hue.toml'))}\nHUE_APPLICATION_KEY=${shellQuote(key)}\n`;
    await writeFile(join(stage,'hue.toml'),config,{mode:0o600,flag:'wx'});
    await writeFile(join(stage,'hue.env'),env,{mode:0o600,flag:'wx'});
    await writeFile(join(stage,'hue-certificate.der'),certificate.raw,{mode:0o600,flag:'wx'});
    const instructions=`# Hue設定の反映\n\n1. hue.toml / hue.env / hue-certificate.der をNanoPiの ${targetDir} に配置します。\n2. root所有にし、設定・認証情報の権限を0600にします。\n3. 既存の /etc/home-sensors.env の末尾に次の行を追加します（既存トークンは保持します）。\n\n    . ${shellQuote(join(targetDir,'hue.env'))}\n\n4. NanoPiからBridge ${bridgeURL(url)} に到達できることを確認します。CLIの接続確認はMacからの確認です。\n5. cloud/migrations/0003_hue.sql を含むD1マイグレーションとWorker更新を行います。\n6. /api/status の cloud.pending が0のタイミングでサービスを再起動します。\n7. Web画面の「照明を選択」で記録対象を選びます。\n\nBridgeの証明書が変わった場合はウィザードを再実行します。\n設定は生成のみで、転送・既存設定の変更・サービス再起動は行っていません。\n`;
    await writeFile(join(stage,'README.md'),instructions,{mode:0o600,flag:'wx'});
    await rename(stage,output);
  }catch(e){await rm(stage,{recursive:true,force:true});throw e;}
}
async function main() {
  const options={output:resolve('.auth/hue'),targetDir:'/etc/home-sensors',subnets:[],discoverOnly:false};
  const args=process.argv.slice(2);
  while(args.length){const arg=args.shift();if(arg==='--help'){console.log('node scripts/hue-setup.mjs [--discover] [--subnet IPv4/CIDR] [--bridge HOST] [--output DIR] [--target-dir /etc/home-sensors] [--key-file FILE]\n--discover は探索結果の表示だけを行います。--subnet は複数指定できます。\n探索はmDNS・SSDP・ARP候補・LAN内HTTPS/HTTP応答確認を行います。\n既存の認証情報は HUE_APPLICATION_KEY または --key-file で渡せます。');return;}if(arg==='--discover'){options.discoverOnly=true;continue;}if(arg==='--subnet'&&args.length){options.subnets.push(args.shift());continue;}const key={'--bridge':'bridge','--output':'output','--target-dir':'targetDir','--key-file':'keyFile'}[arg];if(!key||!args.length)throw Error('引数を確認してください。--help で使用方法を表示します。');options[key]=args.shift();}
  if(options.discoverOnly&&options.bridge)throw Error('--discover と --bridge は同時に指定できません。');
  options.output=resolve(options.output);
  // Reject an occupied output before creating a new application credential.
  if(!options.discoverOnly)try{await stat(options.output);throw Error('出力先が既に存在します。--output で別のディレクトリを指定してください。');}catch(e){if(e.code!=='ENOENT')throw e;}
  const rl=createInterface({input:process.stdin,output:process.stdout});
  try {
    let host=options.bridge;
    if(!host){
      let candidates=[];
      do {
        console.log('LAN内のHue Bridgeを探しています…');
        candidates=await discoverBridges({subnets:options.subnets,onProgress:event=>{
          if(event.type==='start')console.log(`探索範囲: ${event.networks.join(', ')||'IPv4 LANなし'} / ${event.total} アドレス（mDNS・SSDPも並行探索）`);
          if(event.type==='warning')console.log(`探索情報: ${safeText(event.message)}`);
          if(event.type==='neighbors')console.log(`ARP候補 ${event.total} 台を先に確認します。`);
          if(event.type==='multicast')console.log(`${event.source}: ${event.candidates} 候補。HTTPS/HTTP応答で確認します。`);
          if(event.type==='scan'&&(event.completed===0||event.completed%32===0||event.completed===event.total))console.log(`LAN応答確認${event.round===2?'（再試行）':''}: ${event.completed} / ${event.total}`);
          if(event.type==='found')console.log(`Hue応答を確認: ${safeText(event.bridge.name)} / ${event.bridge.host} / ${event.bridge.model}`);
          if(event.type==='retry')console.log(`未確認の ${event.total} アドレスを、待ち時間を延ばして再確認します。`);
          if(event.type==='complete')console.log(`探索完了: ${event.total} アドレスを確認 / Hue Bridge ${event.found} 台`);
        }});
        if(candidates.length)break;
        if(options.discoverOnly){process.exitCode=1;return;}
        const answer=(await rl.question('見つかりませんでした。再探索 [r] / 接続先を手入力 [m] / 中止 [q]: ')).trim().toLowerCase();
        if(answer==='q'){console.log('中止しました。');return;}if(answer==='m')break;
      }while(!candidates.length);
      if(candidates.length){candidates.forEach((b,i)=>console.log(`${i+1}. ${safeText(b.name)} / ${b.host} ${safeText(b.bridgeId)} / ${b.model}（${b.sources.join(', ')}）`));if(options.discoverOnly)return;const answer=await rl.question('Bridge番号（手入力する場合は空欄）: ');if(answer.trim()){const index=Number(answer)-1;if(!Number.isInteger(index)||!candidates[index])throw Error('一覧の番号を選んでください。');host=candidates[index].host;}}
      if(!host)host=await rl.question('BridgeのIPアドレスまたはホスト名: ');
    }
    const url=bridgeURL(host.trim());const certificate=await certificateAt(url);
    const info=await bridgeRequest(url,'/api/config',certificate);
    if(!/^[a-f0-9]{16}$/i.test(info.bridgeid??''))throw Error('Hue Bridgeの識別情報を取得できませんでした。');
    console.log(`Bridge: ${safeText(info.name??'Hue')} / ${info.bridgeid}\n接続先: ${url}\n証明書 SHA-256: ${certificate.fingerprint256}\n証明書の有効期間: ${safeText(certificate.validFrom)} 〜 ${safeText(certificate.validTo)}`);
    if((await rl.question('このBridgeと証明書を信頼して設定しますか？ [yes/N]: ')).trim().toLowerCase()!=='yes'){console.log('中止しました。');return;}
    let key=options.keyFile?(await readFile(options.keyFile,'utf8')).trim():process.env.HUE_APPLICATION_KEY;
    if(!key){
      for(;;){await rl.question('Bridgeのリンクボタンを押してからEnterを押してください: ');
        const paired=await bridgeRequest(url,'/api',certificate,{body:{devicetype:'home-sensors#admin-cli'}});
        key=paired?.[0]?.success?.username;if(key)break;
        if(paired?.[0]?.error?.type!==101)throw Error('ペアリングできませんでした。');
        if((await rl.question('ボタン操作を確認できませんでした。再試行しますか？ [Y/n]: ')).trim().toLowerCase()==='n'){console.log('中止しました。');return;}
      }
    }
    if(!/^[a-z0-9_-]{1,128}$/i.test(key))throw Error('認証情報の形式が不正です。');
    const devices=await bridgeRequest(url,'/clip/v2/resource/device',certificate,{key});
    const lights=await bridgeRequest(url,'/clip/v2/resource/light',certificate,{key});
    if(!Array.isArray(devices.data)||!Array.isArray(lights.data)||!Array.isArray(devices.errors)||devices.errors.length||!Array.isArray(lights.errors)||lights.errors.length)throw Error('API v2で照明を取得できませんでした。Bridgeの対応状況と認証情報を確認してください。');
    console.log(`接続確認: ${lights.data.length} 照明出力を取得しました。`);
    await writeConfiguration(options.output,{url,bridgeId:info.bridgeid,key,certificate,targetDir:options.targetDir});
    console.log(`設定を ${options.output} に生成しました。README.md の手順で反映してください。`);
  }finally{rl.close();}
}
